/** Strip the random "-ab12c" suffix some slugs carry. */
function stripSuffix(key) {
	return key.replace(/-(?=[a-z0-9]{0,4}[0-9])[a-z0-9]{5}$/, "");
}
function curatedRecipeImageUrl(r, size = "card") {
	const candidates = [r.slug, r.name].filter((value) => Boolean(value?.trim()));
	for (const candidate of candidates) {
		const key = curatedKey(candidate);
		for (const k of [
			key,
			stripSuffix(key),
			CURATED_ALIASES[stripSuffix(key)] ?? ""
		]) {
			if (!k) continue;
			const photo = RECIPE_PHOTOS[k];
			if (photo) return photo[size];
			const dish = DISH_PHOTOS[k];
			if (dish) return DISH_RENDITIONS[dish]?.[size] ?? null;
		}
	}
	return null;
}
/** Resize only providers with a known image CDN contract; preserve signed/unknown URLs. */
function photoRendition(url, width) {
	try {
		const parsed = new URL(url);
		if (parsed.protocol !== "https:" || !["images.unsplash.com", "images.pexels.com"].includes(parsed.hostname)) return url;
		if (parsed.searchParams.has("s") || parsed.searchParams.has("signature")) return url;
		parsed.searchParams.set("w", String(width));
		parsed.searchParams.delete("h");
		parsed.searchParams.set("auto", parsed.hostname === "images.pexels.com" ? "compress,format" : "format");
		parsed.searchParams.set("fit", "max");
		parsed.searchParams.set("q", "82");
		return parsed.toString();
	} catch {
		return url;
	}
}
function recipePhotoSources(recipe, size, useCurated = false) {
	const stored = !useCurated && recipe.image_source && recipe.image_url;
	const widths = [
		256,
		512,
		1024
	];
	const sizes = [
		"thumb",
		"card",
		"hero"
	];
	const urls = sizes.map((rendition, i) => stored ? photoRendition(stored, widths[i]) : curatedRecipeImageUrl(recipe, rendition));
	return {
		src: urls[sizes.indexOf(size)] ?? "/recipe-placeholder.svg",
		srcSet: new Set(urls).size > 1 ? urls.map((url, i) => url ? `${url} ${!stored && url.endsWith(".jpg") ? 816 : widths[i]}w` : null).filter(Boolean).join(", ") : void 0
	};
}
