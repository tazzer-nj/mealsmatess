export function findCuratedRecipeBySlug(slug: string): CatalogRecipe | null {
  const clean = slug.trim().toLowerCase();
  if (!clean) return null;
  const exact = CURATED_RECIPES.find((recipe) => recipe.slug.toLowerCase() === clean);
  if (exact) return exact;
  const normalized = clean.replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  return CURATED_RECIPES.find((recipe) => recipe.slug.toLowerCase() === normalized) ?? null;
}

export function findCuratedRecipeById(id: string): CatalogRecipe | null {
  const clean = id.trim();
  if (!clean) return null;
  return CURATED_RECIPES.find((recipe) => recipe.id === clean) ?? null;
}
